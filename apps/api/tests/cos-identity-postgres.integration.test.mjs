import assert from 'node:assert/strict';
import test from 'node:test';
import {randomUUID} from 'node:crypto';
import pg from 'pg';
import {DestinationService} from '../dist/hospital/destination.service.js';
import {UnitsService} from '../dist/admin/units.service.js';
import {captureHsa} from '../dist/authentication/hsa-capture.js';
import {savepointDataSource} from './fixtures/savepoint-data-source.mjs';
const integration=process.env.DATABASE_URL?test:test.skip;
if(process.env.REQUIRE_DATABASE_INTEGRATION&&!process.env.DATABASE_URL)throw new Error('DATABASE_URL required');
integration('COS operational identities and destination revisions enforce group isolation, preserve history and capture only unambiguous HSA',async()=>{
 const client=new pg.Client({connectionString:process.env.DATABASE_URL});await client.connect();await client.query('begin');
 try{
  const database=savepointDataSource(client),{manager,query}=database;
  const group=randomUUID(),child=randomUUID(),other=randomUUID(),actor=randomUUID(),second=randomUUID(),third=randomUUID();
  await query(`insert into app_identity.organization(id,name,deployment_timezone) values($1,'COS identity group','UTC'),($2,'COS other group','UTC')`,[group,other]);
  await query(`insert into app_identity.organization(id,name,deployment_timezone,parent_organization_id) values($1,'Child agency','UTC',$2)`,[child,group]);
  await query(`insert into app_identity.app_user(id,organization_id,display_name) values($1,$2,'COS author'),($3,$4,'Sibling author'),($5,$6,'Other author')`,[actor,group,second,group,third,other]);
  let scope=group;
  const sessions={requireCapability:async(_token,key)=>{assert.ok(['settings:read','settings:write','clinical:document'].includes(key));return {organization:{id:scope},user:{id:actor}};}};
  const directory=new DestinationService(database,sessions),units=new UnitsService(database,sessions);
  const base={displayName:'Hospital / emergency',localCode:'001-ED',hsaId:'HSA-ED',active:true};
  const first=await directory.save('token',null,base);
  const secondUnit=await directory.save('token',null,{...base,displayName:'Hospital / cardiology',localCode:'001-CARD',hsaId:null});
  assert.notEqual(first.id,secondUnit.id);
  scope=child;assert.equal((await directory.list('token')).items.length,2);
  scope=other;assert.equal((await directory.list('token')).items.length,0);
  await assert.rejects(directory.save('token',first.id,{...base,expectedRevision:1}));
  const separate=await directory.save('token',null,base);assert.notEqual(separate.id,first.id);
  scope=group;
  const renamed=await directory.save('token',first.id,{...base,displayName:'Renamed emergency',hsaId:'HSA-NEW',expectedRevision:1});assert.equal(renamed.revision,2);
  await directory.save('token',first.id,{...base,displayName:renamed.displayName,hsaId:renamed.hsaId,active:false,expectedRevision:2});
  assert.equal((await directory.list('token')).items.some(row=>row.id===first.id),false);
  assert.equal((await directory.list('token','',undefined,true)).items.some(row=>row.id===first.id),true);
  await assert.rejects(directory.save('token',null,base));
  assert.deepEqual((await query('select revision,display_name,hsa_id,active from app_identity.destination_revision where group_id=$1 and destination_id=$2 order by revision',[group,first.id])).map(row=>[row.revision,row.display_name,row.hsa_id,row.active]),[[1,base.displayName,base.hsaId,true],[2,renamed.displayName,renamed.hsaId,true],[3,renamed.displayName,renamed.hsaId,false]]);
  const unit=await units.save('token',null,{name:'Ambulance',callSign:`COS-${actor.slice(0,8)}`,rakelId:'001-020',active:true});
  await assert.rejects(units.save('token',null,{name:'Duplicate ambulance',callSign:`DUP-${actor.slice(0,8)}`,rakelId:'001-020',active:true}));
  await units.save('token',unit.id,{name:'Ambulance swapped',callSign:unit.callSign,rakelId:'001-021',active:true,expectedRevision:1});
  const unitEvents=await query('select details from app_identity.operational_unit_event where unit_id=$1 order by id',[unit.id]);
  assert.equal(unitEvents[1].details.before.rakelId,'001-020');assert.equal(unitEvents[1].details.after.rakelId,'001-021');
  const evidence={issuer:'https://issuer.example',subject:'subject',providerRevision:3,providerId:randomUUID()};
  await captureHsa(manager,actor,group,{value:'001-HSA',authoritative:false,finding:null},evidence);
  assert.equal((await query('select hsa_id from app_identity.app_user where id=$1',[actor]))[0].hsa_id,null);
  await captureHsa(manager,actor,group,{value:'001-HSA',authoritative:true,finding:null},evidence);
  assert.equal((await query('select hsa_id,hsa_source from app_identity.app_user where id=$1',[actor]))[0].hsa_source,'oidc');
  await captureHsa(manager,second,child,{value:'001-HSA',authoritative:true,finding:null},evidence);
  assert.deepEqual((await query('select hsa_id,hsa_conflict from app_identity.app_user where id=$1',[second]))[0],{hsa_id:null,hsa_conflict:true});
  await captureHsa(manager,third,other,{value:'001-HSA',authoritative:true,finding:null},evidence);
  assert.equal((await query('select hsa_id from app_identity.app_user where id=$1',[third]))[0].hsa_id,'001-HSA');
  await captureHsa(manager,actor,group,{value:'DIFFERENT',authoritative:true,finding:null},evidence);
  assert.deepEqual((await query('select hsa_id,hsa_conflict from app_identity.app_user where id=$1',[actor]))[0],{hsa_id:'001-HSA',hsa_conflict:true});
  await client.query('savepoint duplicate_hsa');
  await assert.rejects(query('update app_identity.app_user set hsa_id=$2 where id=$1',[second,'001-HSA']),error=>error.code==='23505');
  await client.query('rollback to savepoint duplicate_hsa');
  const events=await query("select details from app_identity.authentication_event where target_user_id=$1 and details->>'operation'='hsa_capture'",[actor]);
  assert.equal(events.length,3);assert.equal(events[0].details.issuer,evidence.issuer);assert.equal(events[0].details.providerRevision,3);
  await client.query('set local role open_triage_api_runtime');
  assert.equal((await query('select count(*)::int n from app_identity.destination_directory where group_id=$1',[group]))[0].n,2);
  await client.query('savepoint immutable_revision');
  await assert.rejects(query('update app_identity.destination_revision set hsa_id=$1 where group_id=$2',['bad',group]));
  await client.query('rollback to savepoint immutable_revision');
 }finally{await client.query('rollback');await client.end();}
});
