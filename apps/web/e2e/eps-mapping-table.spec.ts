import {test,expect} from '@playwright/test';
import {build} from 'esbuild';
import {readFile} from 'node:fs/promises';
import path from 'node:path';

for(const language of ['en','sv']) test(`EPS mapping table edits and responsive layout in ${language}`,async({page})=>{
 const script=(await build({bundle:true,write:false,format:'iife',platform:'browser',jsx:'automatic',define:{'process.env':JSON.stringify({NEXT_PUBLIC_API_URL:'same-origin'})},stdin:{resolveDir:path.resolve(__dirname,'..'),loader:'tsx',contents:`
 import React from 'react';import{createRoot}from'react-dom/client';
 import{HospitalIntegrationsPanel}from'./components/hospital-integrations';
 createRoot(document.getElementById('root')).render(<HospitalIntegrationsPanel language="${language}" csrfToken="fixture" canWrite/>);`}})).outputFiles[0]!.text;
 const css=await readFile(path.resolve(__dirname,'../app/styles.css'),'utf8');
 const field={kind:'nemsis',elementId:'eHistory.06'};
 const mappings=['one','two','three'].map(id=>({id,resourceType:id==='three'?'Condition':'AllergyIntolerance',system:'http://snomed.info/sct',code:id,destination:field,representation:'coded',crosswalk:{system:'urn:target',code:id,display:id,relationship:'equivalent',reference:'https://example.org'}}));
 const view={groupName:'Fixture',stateRevision:1,active:null,activeHealth:'untested',draftHealth:'untested',draft:{revision:1,endpoint:'https://example.org/fhir',credentialConfigured:true,mapping:{sha256:'fixture',definition:{patientIdentifier:{field,namespace:'urn:patient',aliases:[]},clinicalMappings:mappings,outputMappings:[{id:'out',source:{kind:'nemsis',elementId:'eNarrative.01'},section:'patientStory',representation:'signed-narrative'}]}}},options:[],clinicalOptions:['eNarrative.01','ePatient.02'].map(id=>({id,field:{kind:'nemsis',elementId:id},name:id})),tests:[],history:[],events:[]};
 let inspections=0;
 let saved: {clinicalMappings: typeof mappings;outputMappings:{section:string;representation:string;source:{elementId:string}}[]} | undefined;
 await page.route('**/api/admin/hospital/eps',async route=>{
  if(route.request().method()==='PUT'){saved=route.request().postDataJSON();return route.fulfill({json:{...view,draft:{...view.draft,mapping:{...view.draft.mapping,definition:{...view.draft.mapping.definition,clinicalMappings:saved?.clinicalMappings}}}}});}
  return route.fulfill({json:view});
 });
 await page.route('**/api/admin/hospital/eps/inspect-mappings',route=>{inspections++;return route.fulfill({json:route.request().postDataJSON().clinicalMappings.map((m:{id:string})=>({id:m.id,label:m.id,finding:m.id==='three'?'datatype':null}))});});
 await page.route('**/__eps-mappings',route=>route.fulfill({contentType:'text/html',body:`<html lang="${language}"><head><style>${css}</style></head><body style="--green:#663399;--green-dark:#442266"><div id="root"></div><script>${script}</script></body></html>`}));
 await page.goto('/__eps-mappings');
 await expect(page.getByRole('group',{name:language==='en'?'Canonical mapping files':'Kanoniska mappningsfiler',exact:true})).toHaveCount(0);
 await expect(page.locator('input[type=file]')).toHaveCount(0);
 await expect(page.locator('.hospital-integration-status')).toContainText(language==='en'?'Draft revision: 1':'Utkastrevision: 1');
 const table=page.locator('.hospital-mappings-table').first();
 const outgoing=page.locator('.hospital-output-table');
 await expect(outgoing.getByRole('columnheader')).toHaveCount(3);
 await expect(table.getByRole('columnheader')).toHaveCount(3);
 const rows=table.locator('.hospital-mapping-summary');
 await expect(table.getByRole('rowgroup').filter({has:page.locator('th[scope=rowgroup]')})).toHaveCount(2);
 await expect(table.locator('input:visible')).toHaveCount(0);
 await expect(rows).toHaveCount(3);
 await expect(page.getByRole('button',{name:language==='en'?'Check mappings':'Kontrollera mappningar',exact:true})).toHaveCount(0);
 expect(inspections).toBe(0);
 await rows.first().getByRole('button').focus();
 await page.keyboard.press('Enter');
 const target=table.getByLabel(language==='en'?'Destination label':'Målets benämning',{exact:true}).first();
 await target.fill('Edited target');
 await expect(table.getByRole('columnheader')).toHaveCount(3);
 await expect(page.locator('.hospital-mapping-check-summary')).toBeEmpty();
 await page.getByRole('button',{name:'COS',exact:true}).click();
 await page.getByRole('button',{name:'EPS',exact:true}).click();
 await expect(target).toHaveValue('Edited target');
 await rows.nth(1).locator('td').first().click();
 await table.getByRole('button',{name:language==='en'?'Remove mapping':'Ta bort mappning',exact:true}).click();
 await expect(rows).toHaveCount(2);
 await rows.first().getByRole('button').click();
 await expect(target).toHaveValue('Edited target');
 await target.fill('');
 await rows.first().getByRole('button').click();
 await page.getByRole('button',{name:language==='en'?'Save EPS draft':'Spara EPS-utkast',exact:true}).click();
 await expect(target).toBeVisible();
 await expect(target).toBeFocused();
 expect(saved).toBeUndefined();
 expect(inspections).toBe(0);
 await target.fill('Edited target');
 await rows.first().getByRole('button').click();
 await page.getByRole('button',{name:language==='en'?'Save EPS draft':'Spara EPS-utkast',exact:true}).click();
 await expect(table.locator('.hospital-mapping-finding')).toHaveCount(2);
 expect(inspections).toBe(1);
 await expect(rows.first().locator('.hospital-mapping-finding')).toHaveText(language==='en'?'Compatible':'Kompatibel');
 await expect(rows.last().locator('.hospital-mapping-finding')).not.toBeEmpty();
 for(const width of [1440,390]){
  await page.setViewportSize({width,height:900});
  await table.scrollIntoViewIfNeeded();
  await page.locator('.hospital-mappings-scroll').first().evaluate(el=>{el.scrollLeft=0;});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  const region=page.locator('.hospital-mappings-scroll').first();
  await expect(region).toHaveAttribute('tabindex','0');
  await page.screenshot({path:test.info().outputPath(`mappings-${width}.png`),fullPage:true});
  const heading=await page.locator('.eps-integrations > h3').boundingBox();
  const status=await page.locator('.hospital-integration-status').boundingBox();
  const form=await page.locator('.eps-integration-workspace > form').boundingBox();
  expect(heading!.x).toBe(status!.x);
  expect(status!.x).toBe(form!.x);
  await rows.first().getByRole('button').click();
  const editor=page.locator('.hospital-mapping-editor:visible');
  const crosswalk=editor.locator('.hospital-crosswalk-fields > label');
  const system=await crosswalk.nth(1).boundingBox();
  const code=await crosswalk.nth(2).boundingBox();
  expect(system!.y).toBe(code!.y);
  await target.scrollIntoViewIfNeeded();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:test.info().outputPath(`mapping-editor-${width}.png`),fullPage:true});
  await rows.first().getByRole('button').click();
 }
 await rows.first().getByRole('button').click();
 await target.fill('Revised target');
 await expect(table.getByRole('columnheader')).toHaveCount(3);
 await expect(page.locator('.hospital-mapping-check-summary')).toBeEmpty();
 expect(inspections).toBe(1);
 await page.getByRole('combobox',{name:language==='en'?'EPS destination':'EPS-mål',exact:true}).selectOption('patientFamily');
 await expect(page.getByRole('combobox',{name:language==='en'?'Signed source field':'Signerat källfält',exact:true})).toHaveValue('ePatient.02');
 await page.getByRole('button',{name:language==='en'?'Save EPS draft':'Spara EPS-utkast',exact:true}).click();
 await expect.poll(()=>saved?.clinicalMappings?.[0]?.crosswalk?.display).toBe('Revised target');
 await expect.poll(()=>inspections).toBe(2);
 expect(saved?.clinicalMappings).toHaveLength(2);
 expect(saved?.outputMappings[0]).toMatchObject({section:'patientFamily',representation:'structured-patient',source:{elementId:'ePatient.02'}});
});
